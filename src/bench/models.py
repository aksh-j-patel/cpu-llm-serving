"""Model download with pinned revisions and integrity checks.

configs/models.yaml   what to download (repo, files) and which model sets exist
configs/models.lock.json  generated by `bench models lock`: exact Hugging Face commit, size and
                      hash of every file. Committed to git so every machine downloads the same bytes.

Large (LFS) files are checked against their SHA-256; small text files against their git blob
SHA-1, which is what Hugging Face reports for them.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator

import yaml

from bench import paths

CHUNK = 8 * 1024 * 1024
VERIFIED_CACHE = ".verified.json"


class ModelError(RuntimeError):
    pass


@dataclass(frozen=True)
class FileSpec:
    model: str
    repo: str
    revision: str
    filename: str
    size: int
    sha256: str | None
    git_sha1: str | None

    @property
    def expected(self) -> str:
        return f"sha256:{self.sha256}" if self.sha256 else f"git-sha1:{self.git_sha1}"


# ---------------------------------------------------------------- configuration

def load_config(path: Path | None = None) -> dict[str, Any]:
    cfg = yaml.safe_load((path or paths.MODELS_CONFIG).read_text(encoding="utf-8"))
    if "models" not in cfg or "sets" not in cfg:
        raise ModelError("models.yaml must define 'models' and 'sets'")
    return cfg


def resolve_set(name: str, cfg: dict[str, Any] | None = None) -> list[str]:
    """Expand a set name into model keys. Entries starting with '@' include another set."""
    cfg = cfg or load_config()
    sets, seen, out = cfg["sets"], set(), []

    def expand(n: str, stack: tuple[str, ...]) -> None:
        if n not in sets:
            raise ModelError(f"unknown model set '{n}' (known: {', '.join(sets)})")
        if n in stack:
            raise ModelError(f"model set '{n}' includes itself")
        for item in sets[n]:
            if item.startswith("@"):
                expand(item[1:], stack + (n,))
            elif item not in cfg["models"]:
                raise ModelError(f"set '{n}' refers to unknown model '{item}'")
            elif item not in seen:
                seen.add(item)
                out.append(item)

    expand(name, ())
    return out


def load_lock(path: Path | None = None) -> dict[str, Any]:
    p = path or paths.MODELS_LOCK
    if not p.exists():
        raise ModelError(
            f"{p.name} not found. Generate it once with `make lock-models` (needs internet), "
            "then commit it so every machine downloads identical files.")
    return json.loads(p.read_text(encoding="utf-8"))


def file_specs(model_keys: list[str], lock: dict[str, Any] | None = None) -> list[FileSpec]:
    lock = lock or load_lock()
    specs = []
    for key in model_keys:
        entry = lock["models"].get(key)
        if entry is None:
            raise ModelError(f"model '{key}' is missing from models.lock.json; re-run `make lock-models`")
        for f in entry["files"]:
            specs.append(FileSpec(key, entry["repo"], entry["revision"], f["filename"],
                                  int(f["size"]), f.get("sha256"), f.get("git_sha1")))
    return specs


def local_path(spec: FileSpec, models_dir: Path | None = None) -> Path:
    return (models_dir or paths.MODELS_DIR) / spec.model / spec.filename


def model_path(key: str, models_dir: Path | None = None) -> Path:
    """Path to use when loading a model: the .gguf file for single-file models,
    otherwise the directory (Hugging Face format)."""
    cfg = load_config()
    files = cfg["models"][key]["files"]
    base = (models_dir or paths.MODELS_DIR) / key
    return base / files[0] if len(files) == 1 and files[0].endswith(".gguf") else base


# ---------------------------------------------------------------- hashing / verification

def _chunks(path: Path) -> Iterator[bytes]:
    with path.open("rb") as fh:
        while chunk := fh.read(CHUNK):
            yield chunk


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    for c in _chunks(path):
        h.update(c)
    return h.hexdigest()


def git_blob_sha1(path: Path) -> str:
    h = hashlib.sha1()
    h.update(f"blob {path.stat().st_size}\0".encode())
    for c in _chunks(path):
        h.update(c)
    return h.hexdigest()


def _cache_file(models_dir: Path) -> Path:
    return models_dir / VERIFIED_CACHE


def _load_cache(models_dir: Path) -> dict[str, Any]:
    try:
        return json.loads(_cache_file(models_dir).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _save_cache(models_dir: Path, cache: dict[str, Any]) -> None:
    models_dir.mkdir(parents=True, exist_ok=True)
    _cache_file(models_dir).write_text(json.dumps(cache, indent=1), encoding="utf-8")


def verify_file(spec: FileSpec, models_dir: Path | None = None, read_cache: bool = True) -> tuple[bool, str]:
    """Return (ok, reason). Hashing is skipped if the file is unchanged since it last verified
    (unless read_cache is False). A successful hash check is always recorded in the cache."""
    models_dir = models_dir or paths.MODELS_DIR
    p = local_path(spec, models_dir)
    if not p.exists():
        return False, "missing"
    st = p.stat()
    if st.st_size != spec.size:
        return False, f"size {st.st_size} != expected {spec.size}"
    key = f"{spec.model}/{spec.filename}"
    cache = _load_cache(models_dir) if read_cache else {}
    hit = cache.get(key)
    if hit and hit == {"size": st.st_size, "mtime_ns": st.st_mtime_ns, "expected": spec.expected}:
        return True, "ok (cached)"
    actual = sha256_file(p) if spec.sha256 else git_blob_sha1(p)
    expected = spec.sha256 or spec.git_sha1
    if actual != expected:
        return False, f"hash mismatch: got {actual[:12]}..., expected {expected[:12]}..."
    cache = _load_cache(models_dir)
    cache[key] = {"size": st.st_size, "mtime_ns": st.st_mtime_ns, "expected": spec.expected}
    _save_cache(models_dir, cache)
    return True, "ok"


# ---------------------------------------------------------------- lock / download

def _lfs_sha256(sibling: Any) -> str | None:
    lfs = getattr(sibling, "lfs", None)
    if lfs is None:
        return None
    return lfs.get("sha256") if isinstance(lfs, dict) else getattr(lfs, "sha256", None)


def _lfs_size(sibling: Any) -> int | None:
    lfs = getattr(sibling, "lfs", None)
    if lfs is None:
        return None
    return lfs.get("size") if isinstance(lfs, dict) else getattr(lfs, "size", None)


def lock(model_keys: list[str] | None = None, revision: str = "main") -> dict[str, Any]:
    """Query Hugging Face for the current commit and file hashes and write models.lock.json."""
    import huggingface_hub
    from huggingface_hub import HfApi

    cfg = load_config()
    keys = model_keys or list(cfg["models"])
    existing = load_lock() if paths.MODELS_LOCK.exists() else {"models": {}}
    api = HfApi()
    infos: dict[tuple[str, str], Any] = {}
    for key in keys:
        m = cfg["models"][key]
        rev = m.get("revision", revision)
        if (m["repo"], rev) not in infos:
            infos[(m["repo"], rev)] = api.model_info(m["repo"], revision=rev, files_metadata=True)
        info = infos[(m["repo"], rev)]
        siblings = {s.rfilename: s for s in info.siblings or []}
        files = []
        for fname in m["files"]:
            s = siblings.get(fname)
            if s is None:
                raise ModelError(f"{m['repo']}@{info.sha[:10]} has no file '{fname}'")
            sha256 = _lfs_sha256(s)
            size = s.size if s.size is not None else _lfs_size(s)
            files.append({"filename": fname, "size": int(size), "sha256": sha256,
                          "git_sha1": None if sha256 else s.blob_id})
        existing["models"][key] = {"repo": m["repo"], "revision": info.sha, "files": files}
        print(f"  locked {key:24s} {m['repo']}@{info.sha[:10]} ({len(files)} files)")
    existing["generated_utc"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    existing["huggingface_hub"] = huggingface_hub.__version__
    existing["models"] = dict(sorted(existing["models"].items()))
    paths.MODELS_LOCK.write_text(json.dumps(existing, indent=2) + "\n", encoding="utf-8")
    return existing


def human(n: float) -> str:
    for unit in ("B", "KB", "MB"):
        if n < 1024:
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.2f} GB"


def download_keys(keys: list[str], label: str, models_dir: Path | None = None) -> list[FileSpec]:
    """Download (if needed) and verify the files of the given models. Raises ModelError on failure."""
    from huggingface_hub import hf_hub_download

    models_dir = models_dir or paths.MODELS_DIR
    specs = file_specs(keys)
    total = sum(s.size for s in specs)
    print(f"Models '{label}': {len(specs)} files, {human(total)}")
    failures = []
    for s in specs:
        ok, reason = verify_file(s, models_dir)
        if not ok:
            if reason != "missing":
                print(f"  {s.model}/{s.filename}: {reason}; downloading again")
            print(f"  downloading {s.repo}/{s.filename} ({human(s.size)}) @ {s.revision[:10]}")
            hf_hub_download(repo_id=s.repo, filename=s.filename, revision=s.revision,
                            local_dir=str(models_dir / s.model))
            ok, reason = verify_file(s, models_dir, read_cache=False)
        print(f"  [{'OK' if ok else 'FAIL'}] {s.model}/{s.filename}: {reason}")
        if not ok:
            failures.append(f"{s.model}/{s.filename}: {reason}")
    if failures:
        raise ModelError("verification failed:\n  " + "\n  ".join(failures))
    return specs


def download(set_name: str, models_dir: Path | None = None) -> list[FileSpec]:
    """Download (if needed) and verify every file of a model set."""
    return download_keys(resolve_set(set_name), set_name, models_dir)


def lock_entry(key: str) -> dict[str, Any] | None:
    """The lock entry (repo, revision, file hashes) for one model, for result metadata."""
    try:
        return load_lock()["models"].get(key)
    except ModelError:
        return None


def verify(set_name: str, models_dir: Path | None = None) -> bool:
    all_ok = True
    for s in file_specs(resolve_set(set_name)):
        ok, reason = verify_file(s, models_dir)
        all_ok &= ok
        print(f"  [{'OK' if ok else 'FAIL'}] {s.model}/{s.filename}: {reason}")
    return all_ok


def describe(set_name: str | None = None) -> list[str]:
    cfg = load_config()
    lock_data = load_lock() if paths.MODELS_LOCK.exists() else None
    lines = []
    for name in cfg["sets"] if set_name is None else [set_name]:
        keys = resolve_set(name, cfg)
        size = ""
        if lock_data:
            try:
                size = f" ({human(sum(s.size for s in file_specs(keys, lock_data)))})"
            except ModelError:
                size = " (lock incomplete)"
        lines.append(f"{name}{size}: {', '.join(keys)}")
    return lines
